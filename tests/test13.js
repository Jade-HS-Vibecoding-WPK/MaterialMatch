const PROJ = require('path').resolve(__dirname, '..');
const AUSGABE = require('path').join(require('os').tmpdir(), 'materialmatch-tests') + '/';
require('fs').mkdirSync(AUSGABE, { recursive: true });
const B = require(PROJ + '/js/berechnung.js');
const W = require(PROJ + '/js/bewertung.js');
let fails = 0;
const ok = (n, c, x) => { if (!c) fails++; console.log((c ? 'OK   ' : 'FAIL ') + n + (c || x === undefined ? '' : ' -> ' + JSON.stringify(x))); };
const near = (a, b, e = 1e-9) => Math.abs(a - b) <= e * Math.max(1, Math.abs(b));

// Testmaterialien (frei gewählte Zahlen, Rechenwege von Hand geprüft)
const mat = (o) => Object.assign({ mengenmodell: 'schicht', eigenschaften: {} }, o);
const rho = w => ({ wert: w, einheit: 'kg/m³' });
const preis = (w, e, x = {}) => Object.assign({ wert: w, einheit: e, mwst: 'netto', umfang: 'Material' }, x);
const gwp = (g, f, b, bezug, x = {}) => Object.assign({ werte: { gesamt: g, fossil: f, biogen: b }, einheit: 'kg CO2e', deklarierte_einheit: bezug, module: 'A1-A3' }, x);

const beton = mat({ eigenschaften: { rohdichte: rho(2300), preis: preis(140, '€/m³'), gwp: gwp(221.656798081968, 221.752392594831, -0.348896333462629, '1 m³'), waermeleitfaehigkeit: { wert: 2.0 } } });
const epsKg = mat({ eigenschaften: { rohdichte: rho(15), preis: preis(1.2, '€/kg'), gwp: gwp(3, 3, 0, '1 kg'), waermeleitfaehigkeit: { wert: 0.035 } } });
const stahl = mat({ mengenmodell: 'keine_schicht', eigenschaften: { rohdichte: rho(7850), preis: preis(1.3, '€/kg'), gwp: gwp(0.56, 0.56, 0, '1 kg'), waermeleitfaehigkeit: { wert: 50 } } });
const dach = mat({ mengenmodell: 'keine_schicht', eigenschaften: { preis: preis(12, '€/m²'), gwp: gwp(16.588, 16.549, 0.025, '1 m²') } });
const platte = mat({ eigenschaften: { rohdichte: rho(800), preis: preis(5, '€/m²', { bezugsdicke_m: 0.0125 }), gwp: gwp(1.01387, 1.0, 0, '1 m²', { bezugsdicke_m: 0.0125 }) } });

console.log('--- Eingaben: einzeln gültige Werte ---');
const E = (f, d, u = 'cm') => B.pruefeEingaben({ flaecheText: f, dickeText: d, dickeEinheit: u });
let e = E('100', ''); ok('Nur Fläche: flaeche_gueltig 100, dicke_gueltig null', e.flaeche_gueltig_m2 === 100 && e.dicke_gueltig_m === null && e.status === 'unvollstaendig', e);
e = E('', '20'); ok('Nur Dicke: dicke_gueltig 0,2 m', e.flaeche_gueltig_m2 === null && near(e.dicke_gueltig_m, 0.2), e);
e = E('-5', '20'); ok('Negative Fläche: nicht gültig, Dicke trotzdem gültig', e.flaeche_gueltig_m2 === null && near(e.dicke_gueltig_m, 0.2) && e.status === 'fehler', e);
e = E('100', '200', 'mm'); ok('200 mm -> dicke_gueltig 0,2 m', near(e.dicke_gueltig_m, 0.2) && e.status === 'ok');
e = E('abc', 'x'); ok('Beide ungültig: beide null', e.flaeche_gueltig_m2 === null && e.dicke_gueltig_m === null);
e = E('100', '0'); ok('Dicke 0: Dicke nicht gültig', e.dicke_gueltig_m === null && e.flaeche_gueltig_m2 === 100);

console.log('--- Bezugsmenge ---');
let m = B.mengeFuerBezug('1 m³', beton, 100, 0.2);
ok('1 m³: Volumen 20', m.moeglich && near(m.menge, 20) && m.einheit === 'm³', m);
m = B.mengeFuerBezug('1 kg', epsKg, 100, 0.2);
ok('1 kg: Gewicht 20 × 15 = 300 kg', m.moeglich && near(m.menge, 300) && m.einheit === 'kg', m);
m = B.mengeFuerBezug('1 m²', dach, 100, 0.2);
ok('1 m² bei Material ohne Schicht: Fläche 100 (Dicke egal)', m.moeglich && m.menge === 100 && m.einheit === 'm²', m);
m = B.mengeFuerBezug('1 m²', platte, 100, 0.0125, 0.0125);
ok('1 m² Schicht mit passender Bezugsdicke: Fläche 100', m.moeglich && m.menge === 100, m);
m = B.mengeFuerBezug('1 m²', platte, 100, 0.025, 0.0125);
ok('1 m² Schicht, Dicke weicht ab: nicht möglich, nennt 12,5 und 25 mm', !m.moeglich && m.grund.includes('12,5 mm') && m.grund.includes('25 mm'), m);
m = B.mengeFuerBezug('1 m²', platte, 100, 0.0125, undefined);
ok('1 m² Schicht ohne Bezugsdicke: nicht möglich', !m.moeglich && m.grund.includes('nicht angegebene Dicke'), m);
m = B.mengeFuerBezug('1 m³', stahl, 100, 0.2);
ok('1 m³ bei Material ohne Schicht: nicht möglich', !m.moeglich && m.grund.includes('keine Schichtberechnung'), m);
m = B.mengeFuerBezug('1 kg', stahl, 100, 0.2);
ok('1 kg bei Material ohne Schicht: nicht möglich', !m.moeglich, m);
m = B.mengeFuerBezug('1 kg', mat({ eigenschaften: {} }), 100, 0.2);
ok('1 kg ohne Rohdichte: nicht möglich (Rohdichte fehlt)', !m.moeglich && m.grund.includes('Rohdichte fehlt'), m);
m = B.mengeFuerBezug('1 Sack', beton, 100, 0.2);
ok('Unbekannte Bezugsgröße: nicht möglich', !m.moeglich && m.grund.includes('Unbekannte'), m);
m = B.mengeFuerBezug('1 m²', platte, 100, 0.0125 + 1e-12, 0.0125);
ok('Rundungsrauschen bei der Dicke (1e-12) zählt als gleich', m.moeglich, m);

console.log('--- Materialkosten ---');
let k = B.berechneKosten(beton, 100, 0.2);
ok('Beton: 20 m³ × 140 €/m³ = 2.800 €', k.moeglich && near(k.kosten_eur, 2800) && k.mengeneinheit === 'm³' && !k.umweg, k);
k = B.berechneKosten(epsKg, 100, 0.2);
ok('€/kg über Gewicht: 300 kg × 1,2 = 360 €, Umweg markiert', k.moeglich && near(k.kosten_eur, 360) && k.umweg === true && k.mengeneinheit === 'kg', k);
k = B.berechneKosten(dach, 100, 0.2);
ok('€/m² ohne Schicht: 100 m² × 12 = 1.200 €', k.moeglich && near(k.kosten_eur, 1200) && k.mengeneinheit === 'm²', k);
k = B.berechneKosten(platte, 100, 0.0125);
ok('€/m² Schicht bei passender Dicke: 100 × 5 = 500 €', k.moeglich && near(k.kosten_eur, 500), k);
k = B.berechneKosten(platte, 100, 0.025);
ok('€/m² Schicht bei abweichender Dicke: nicht berechenbar (keine Annahme)', !k.moeglich, k);
k = B.berechneKosten(stahl, 100, 0.2);
ok('Baustahl €/kg ohne Schicht: nicht berechenbar', !k.moeglich && k.grund.includes('Gewicht'), k);
k = B.berechneKosten(mat({ eigenschaften: { preis: { wert: null, einheit: '€/m³' } } }), 100, 0.2);
ok('Preis fehlt: nicht berechenbar, "Preis fehlt"', !k.moeglich && k.grund.includes('Preis fehlt'), k);
k = B.berechneKosten(mat({ eigenschaften: {} }), 100, 0.2);
ok('Keine Preisangabe überhaupt: nicht berechenbar', !k.moeglich);
k = B.berechneKosten(beton, 0.5, 0.01);
ok('Kleine Menge: 0,005 m³ × 140 = 0,70 €', near(k.kosten_eur, 0.7), k);
k = B.berechneKosten(beton, 1000000, 10);
ok('Größte zulässige Eingabe: 1.000.000 m² × 10 m = 10 Mio. m³ -> 1,4 Mrd. €', near(k.kosten_eur, 1.4e9), k);

console.log('--- CO₂-Menge ---');
let c = B.berechneCo2(beton, 100, 0.2);
ok('Beton: 20 m³ × Kennwert (gesamt, fossil, biogen)', c.moeglich && near(c.gesamt, 20 * 221.656798081968) && near(c.fossil, 20 * 221.752392594831) && near(c.biogen, 20 * -0.348896333462629), c);
ok('Echter Datensatz: gesamt ≠ fossil + biogen, der Rest ist luluc (hier nicht im Testmaterial)', c.luluc === null && !near(c.gesamt, c.fossil + c.biogen, 1e-6), [c.gesamt, c.fossil + c.biogen, c.luluc]);
const mitLuluc = mat({ eigenschaften: { rohdichte: rho(1000), gwp: { werte: { gesamt: 10, fossil: 8, biogen: 1, luluc: 1 }, einheit: 'kg CO2e', deklarierte_einheit: '1 m³', module: 'A1-A3' } } });
const cl = B.berechneCo2(mitLuluc, 100, 0.2);
ok('Mit luluc: 20 m³ -> gesamt 200, fossil 160, biogen 20, luluc 20', near(cl.gesamt, 200) && near(cl.fossil, 160) && near(cl.biogen, 20) && near(cl.luluc, 20), cl);
ok('Mit luluc: gesamt = fossil + biogen + luluc', near(cl.gesamt, cl.fossil + cl.biogen + cl.luluc), cl);
ok('Module und Bezugsgröße werden mitgeführt', c.module === 'A1-A3' && c.bezug === '1 m³' && c.mengeneinheit === 'm³');
c = B.berechneCo2(epsKg, 100, 0.2);
ok('je kg: 300 kg × 3 = 900 kg CO₂e', c.moeglich && near(c.gesamt, 900) && c.umweg === true, c);
c = B.berechneCo2(dach, 100, 0.2);
ok('je m² ohne Schicht: 100 m² × 16,588 = 1.658,8 kg CO₂e', near(c.gesamt, 1658.8), c);
c = B.berechneCo2(platte, 100, 0.0125);
ok('je m² Schicht bei Bezugsdicke: 100 × 1,01387 = 101,387', near(c.gesamt, 101.387), c);
c = B.berechneCo2(platte, 100, 0.02);
ok('je m² Schicht, falsche Dicke: nicht berechenbar', !c.moeglich, c);
c = B.berechneCo2(stahl, 100, 0.2);
ok('Baustahl je kg ohne Schicht: nicht berechenbar', !c.moeglich, c);
c = B.berechneCo2(mat({ eigenschaften: { gwp: { werte: null } } }), 100, 0.2);
ok('CO₂-Kennwert fehlt: nicht berechenbar', !c.moeglich && c.grund.includes('fehlt'), c);

console.log('--- R-Wert R = d / λ ---');
let r = B.berechneR(epsKg, 0.2);
ok('d = 0,2 m, λ = 0,035: R = 5,714 m²K/W', r.moeglich && near(r.R, 0.2 / 0.035), r);
r = B.berechneR(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: 0.04 } } }), 0.2);
ok('d = 0,2 m, λ = 0,04: R = 5,0', near(r.R, 5), r);
r = B.berechneR(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: 0.035 } } }), 0.1);
ok('Halbe Dicke, halbes R (2,857)', near(r.R, 0.1 / 0.035));
r = B.berechneR(stahl, 0.2);
ok('Material ohne Schicht: kein R-Wert', !r.moeglich && r.grund.includes('Keine homogene Schicht'), r);
r = B.berechneR(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: null, nicht_anwendbar: true } } }), 0.2);
ok('λ nicht anwendbar: kein R-Wert', !r.moeglich && r.grund.includes('nicht anwendbar'), r);
r = B.berechneR(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: null } } }), 0.2);
ok('λ fehlt: kein R-Wert', !r.moeglich && r.grund.includes('fehlt'), r);
r = B.berechneR(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: 0 } } }), 0.2);
ok('λ = 0: keine Division durch null', !r.moeglich && r.grund.includes('ungültig'), r);
r = B.berechneR(mat({ eigenschaften: {} }), 0.2);
ok('Keine λ-Angabe: kein R-Wert', !r.moeglich);
r = B.berechneR(beton, 0.2);
ok('Beton: R = 0,2 / 2,0 = 0,1 (rechnerisch möglich)', near(r.R, 0.1), r);

console.log('--- Erforderliche Dicke d = R × λ ---');
let d = B.erforderlicheDicke(epsKg, 5);
ok('R = 5, λ = 0,035: d = 0,175 m (17,5 cm)', d.moeglich && near(d.dicke_m, 0.175), d);
d = B.erforderlicheDicke(mat({ eigenschaften: { waermeleitfaehigkeit: { wert: 0.04 } } }), 6);
ok('R = 6, λ = 0,04: d = 0,24 m', near(d.dicke_m, 0.24), d);
ok('Probe: R(d(R)) = R', near(B.berechneR(epsKg, B.erforderlicheDicke(epsKg, 4.2).dicke_m).R, 4.2));
d = B.erforderlicheDicke(beton, 10);
ok('Beton: R = 10 braucht 20 m -> unplausibel, nicht möglich', !d.moeglich && d.grund.includes('unplausibel') && d.grund.includes('20'), d);
d = B.erforderlicheDicke(beton, 5);
ok('Genau 10 m (Grenze): noch möglich', d.moeglich && near(d.dicke_m, 10), d);
d = B.erforderlicheDicke(beton, 5.0001);
ok('Knapp über 10 m: nicht möglich', !d.moeglich, d);
d = B.erforderlicheDicke(stahl, 2);
ok('Material ohne Schicht: keine erforderliche Dicke', !d.moeglich, d);

console.log('--- Gewünschter R-Wert (Eingabe) ---');
const R = t => B.pruefeRZiel(t);
ok('"5" ok', R('5').status === 'ok' && R('5').r === 5);
ok('"5,5" ok', R('5,5').r === 5.5);
ok('"5.5" ok', R('5.5').r === 5.5);
ok('leer: Status leer, kein Fehler', R('').status === 'leer' && R('  ').fehler === null);
ok('"0": Fehler größer als 0', R('0').status === 'fehler' && R('0').fehler.includes('größer als 0'));
ok('"-1": Fehler negativ', R('-1').fehler.includes('negativ'));
ok('"abc": Fehler Zahl', R('abc').status === 'fehler' && R('abc').fehler.includes('Zahl'));
ok('"50" noch ok', R('50').status === 'ok');
ok('"50,1" zu groß', R('50,1').status === 'fehler' && R('50,1').fehler.includes('unplausibel'));
ok('"1.500" mehrdeutig -> Fehler', R('1.500').status === 'fehler' && R('1.500').fehler.includes('Unklar'));

console.log('--- Euro-Format ---');
[[2800, '2.800'], [12.5, '12,5'], [0.4, '0,4'], [99.999, '100'], [100, '100'], [1234567, '1.234.567'], [0, '0'], [-300, '-300'], [-2.5, '-2,5'], [1.4e9, '1.400.000.000']].forEach(([x, s]) => ok(`formatEuro(${x}) = "${s}"`, B.formatEuro(x) === s, B.formatEuro(x)));
ok('formatEuro(NaN) = "–"', B.formatEuro(NaN) === '–' && B.formatEuro(null) === '–');

console.log('--- Vergleichbarkeit nach Umrechnung ---');
const Q = { g: { typ: 'generic dataset' }, a: { typ: 'average dataset' } }; const qf = id => Q[id] || null;
let v = W.pruefeCo2([gwp(1, 1, 0, '1 m³', { quelle: 'g' }), gwp(1, 1, 0, '1 kg', { quelle: 'g' })], qf, { ohneEinheit: true });
ok('Mit Umrechnung: verschiedene Bezugsgrößen sind kein Problem mehr', v.probleme.length === 0 && v.zusatz.length === 0 && !v.gleicheEinheit, v);
v = W.pruefeCo2([gwp(1, 1, 0, '1 m³', { quelle: 'g' }), gwp(1, 1, 0, '1 kg', { quelle: 'g' })], qf);
ok('Ohne Umrechnung (Kennwertvergleich): weiterhin Problem', v.probleme.length === 1 && v.zusatz[0].includes('weiter oben'), v);
v = W.pruefeCo2([gwp(1, 1, 0, '1 m³', { quelle: 'g' }), gwp(1, 1, 0, '1 kg', { quelle: 'a' })], qf, { ohneEinheit: true });
ok('Mit Umrechnung bleiben verschiedene Datensatztypen ein Problem', v.probleme.length === 1 && v.probleme[0].includes('Datensatztypen'), v);
v = W.pruefeCo2([gwp(1, 1, 0, '1 m³', { quelle: 'g', module: 'A1-A3' }), gwp(1, 1, 0, '1 m³', { quelle: 'g', module: 'A1-A3, C3' })], qf, { ohneEinheit: true });
ok('Mit Umrechnung bleiben verschiedene Module ein Problem', v.probleme.length === 1 && v.probleme[0].includes('Lebenszyklusmodule'), v);
ok('Preis-Hinweistext verweist auf berechnete Kosten statt auf "Schritt 7"', W.pruefePreis([preis(1, '€/m³'), preis(1, '€/kg')]).probleme[0].includes('berechneten Materialkosten'));

console.log(fails === 0 ? '\nALLE TESTS BESTANDEN' : '\nFEHLGESCHLAGEN: ' + fails);
